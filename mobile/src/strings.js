/** Fill the directory templates for a property (its tokens and its directory terms). */
export function fillPlaces(property) {
  return remoteStringOverlay(fillDeep(placesTemplates, { ...propertyTokens(property), ...directoryTerms(property) }), 'mobile.places', { lookup: (key) => remoteStringFor(key, property) });
}

/**
 * The remote override of a catalog key (docs/LIVE_UPDATES_CONTRACT.md section 14.3) with the
 * property tokens filled (plus the directory terms under `mobile.places`), or undefined.
 * @param {string} key For example `mobile.common.retry`.
 * @param {object} [property]
 */
export function remoteStringFor(key, property = getBundledProperty()) {
  const value = remoteStringValue(key);
  if (value === undefined) return undefined;
  const tokens = key.startsWith('mobile.places.') ? { ...propertyTokens(property), ...directoryTerms(property) } : propertyTokens(property);
  return formatTemplate(value, tokens);
}

