/**
 * Jest configuration (jest-expo preset).
 *
 * Tests run against the active property (TK_PROPERTY_DIR, default: the neutral sample at
 * samples/example). `tk-property/<file>` imports resolve to that property's mobile/ folder, the
 * same mapping metro.config.js applies to app builds.
 */
const path = require('path');
const { resolvePropertyDir } = require('./scripts/property');

const propertyMobileDir = path.join(resolvePropertyDir(), 'mobile');

// jest-expo's patterns, plus @shopify/flash-list (published as ES modules).
const expoIgnore = require('jest-expo/jest-preset').transformIgnorePatterns || [];
const transformIgnorePatterns = expoIgnore.map((pattern) => pattern.replace('|expo|', '|expo|@shopify/flash-list|'));

module.exports = {
  preset: 'jest-expo',
  // Full-screen render tests are slow on shared CI runners; the default 5 s per test is too tight there.
  testTimeout: 60000,
  modulePaths: ['<rootDir>/node_modules'],
  // Native projects generated by `expo prebuild` or `expo run:*` (git ignored) contain copies of
  // JavaScript packages; without this, Jest's module map picks them up and every render suite fails.
  modulePathIgnorePatterns: ['<rootDir>/ios/', '<rootDir>/android/'],
  testPathIgnorePatterns: ['/node_modules/', '<rootDir>/ios/', '<rootDir>/android/'],
  setupFilesAfterEnv: ['<rootDir>/jest.setup.js'],
  transformIgnorePatterns,
  moduleNameMapper: {
    '^tk-property/(.*)$': propertyMobileDir.split(path.sep).join('/') + '/$1'
  }
};
