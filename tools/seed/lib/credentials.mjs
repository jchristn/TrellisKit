// Local credentials file (Markdown table). Holds random local-only passwords; keep it git-ignored.

import { readFile, writeFile } from 'node:fs/promises';

export async function readCredentials(file) {
  const out = new Map();
  let text;
  try {
    text = await readFile(file, 'utf8');
  } catch {
    return out;
  }
  for (const line of text.split('\n')) {
    const cells = line.split('|').map((c) => c.trim());
    // | key | name | email | password | ... |
    if (cells.length < 6 || !cells[1] || cells[1] === 'Key' || /^-+$/.test(cells[1])) continue;
    const password = cells[4].replace(/^`|`$/g, '');
    const email = cells[3].replace(/^`|`$/g, '');
    if (password && email.includes('@')) out.set(cells[1].replace(/^`|`$/g, ''), { email, password });
  }
  return out;
}

export async function writeCredentials(file, { title, webBaseUrl, adminUrl, rows, extra = [] }) {
  const lines = [
    `# ${title}`,
    '',
    'Generated by the TrellisKit seeding tool. These are random, local-only passwords for the local Docker stack.',
    'This file is git-ignored; never commit it and never reuse these passwords anywhere else.',
    '',
    `Website: ${webBaseUrl} (admin console: ${adminUrl})`,
    '',
    '| Key | Name | Email | Password | Roles | Membership | Notes |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const r of rows) {
    lines.push(`| ${r.key} | ${r.name} | \`${r.email}\` | \`${r.password}\` | ${r.roles || 'Member'} | ${r.membership} | ${r.notes ?? ''} |`);
  }
  if (extra.length) lines.push('', ...extra);
  lines.push('');
  await writeFile(file, lines.join('\n'), { mode: 0o600 });
}
