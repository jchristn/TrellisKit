#!/bin/sh
# RecallDB container start script (POSIX sh), mounted read-only into the jchristn77/recalldb-server image.
#
# The image reads /app/recalldb.json, and its defaults bind the web server to localhost only (unreachable from other
# containers and from the published host port) with the well-known admin API key recalldbadmin. The image has no
# environment variable for either, so this script writes the settings file before every start:
#   - Webserver.Hostname "*" (all interfaces) on RECALLDB_PORT (default 8600);
#   - AdminApiKeys from RECALLDB_ADMIN_API_KEY (docker/.env.local, generated by env-local.sh);
#   - Database.RequireEncryption from RECALLDB_DB_REQUIRE_ENCRYPTION (false locally).
# Database host, name, user, password, and schema, MCP, and observability still come from the image's own
# RECALLDB_* environment variables, which override the file.
#
# After the server answers, it makes sure the TrellisKit server's credential exists: a bearer token
# (RECALLDB_SERVER_TOKEN, the server's TK_RECALLDB_TOKEN) on tenant RECALLDB_TENANT (default "default") for that
# tenant's seeded user. It then deletes the image's seeded credential, whose bearer token is the well-known value
# "default". Both steps are idempotent.
#
# The AWS RecallDB task runs this same file (infra reads it at synth time). Plain $NAME expansions are used where
# possible so CloudFormation validation does not mistake them for template parameters.
set -eu

: "${RECALLDB_ADMIN_API_KEY:?RECALLDB_ADMIN_API_KEY is required}"
: "${RECALLDB_SERVER_TOKEN:?RECALLDB_SERVER_TOKEN is required}"
: "${RECALLDB_TENANT:=default}"
: "${RECALLDB_PORT:=8600}"
: "${RECALLDB_DB_REQUIRE_ENCRYPTION:=false}"
: "${RECALLDB_SETTINGS_FILE:=/app/recalldb.json}"

cat > "$RECALLDB_SETTINGS_FILE" <<JSON
{
  "Webserver": { "Hostname": "*", "Port": $RECALLDB_PORT, "Ssl": false },
  "Database": {
    "Hostname": "localhost",
    "Port": 5432,
    "DatabaseName": "recalldb",
    "Username": "recalldb",
    "Password": "",
    "Schema": "public",
    "RequireEncryption": $RECALLDB_DB_REQUIRE_ENCRYPTION,
    "LogQueries": false,
    "MigrateFullTextColumn": true,
    "SchemaCommandTimeoutSeconds": 0
  },
  "Logging": {
    "ConsoleLogging": true,
    "EnableColors": false,
    "MinimumSeverity": 0,
    "LogDirectory": "./logs/",
    "LogFilename": "recalldb.log",
    "FileLogging": false,
    "IncludeDateInFilename": true,
    "Servers": []
  },
  "Debug": { "Authentication": false, "Exceptions": true, "Requests": false, "DatabaseQueries": false },
  "Mcp": { "Enabled": false, "Hostname": "127.0.0.1", "Port": 8620, "ServerName": "RecallDB.McpServer", "ServerVersion": "0.2.1", "LogOperations": false },
  "Observability": {
    "Enabled": false,
    "ServiceName": "recalldb-server",
    "PrometheusEnabled": true,
    "PrometheusHostname": "*",
    "PrometheusPort": 9464,
    "PrometheusPath": "/metrics",
    "TracingEnabled": true,
    "OtlpEndpoint": "http://localhost:4317",
    "OtlpProtocol": "grpc",
    "SamplingRatio": 1,
    "IncludeRuntimeMetrics": true,
    "IncludeProcessMetrics": true
  },
  "AdminApiKeys": [ "$RECALLDB_ADMIN_API_KEY" ]
}
JSON

dotnet RecallDb.Server.dll &
child=$!
trap 'kill -TERM "$child" 2>/dev/null' TERM INT

base="http://127.0.0.1:$RECALLDB_PORT"
tries=0
until curl -fsS -o /dev/null "$base/"; do
  tries=$((tries + 1))
  if [ "$tries" -ge 120 ]; then echo "recalldb-start: server did not answer within 120 s" >&2; kill -TERM "$child"; exit 1; fi
  if ! kill -0 "$child" 2>/dev/null; then echo "recalldb-start: server exited" >&2; wait "$child"; exit 1; fi
  sleep 1
done

status() { curl -sS -o /dev/null -w '%{http_code}' -H "Authorization: Bearer $1" "$base/v1.0/tenants/$RECALLDB_TENANT/collections"; }
admin() { curl -fsS -o /dev/null -H "Authorization: Bearer $RECALLDB_ADMIN_API_KEY" -H "Content-Type: application/json" "$@"; }

if [ "$(status "$RECALLDB_SERVER_TOKEN")" = "200" ]; then
  echo "recalldb-start: server credential present on tenant $RECALLDB_TENANT"
else
  admin -X PUT -d "{\"UserId\":\"default\",\"Name\":\"TrellisKit server\",\"BearerToken\":\"$RECALLDB_SERVER_TOKEN\"}" "$base/v1.0/tenants/$RECALLDB_TENANT/credentials"
  echo "recalldb-start: created the server credential on tenant $RECALLDB_TENANT"
fi

if [ "$RECALLDB_SERVER_TOKEN" != "default" ] && [ "$(status default)" = "200" ]; then
  admin -X DELETE "$base/v1.0/tenants/$RECALLDB_TENANT/credentials/default" && echo "recalldb-start: removed the seeded credential with the well-known token"
fi

wait "$child"
