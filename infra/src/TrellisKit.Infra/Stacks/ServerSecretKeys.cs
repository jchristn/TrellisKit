namespace TrellisKit.Infra.Stacks
{
    using System.Collections.Generic;

    /// <summary>
    /// Environment variables the server reads from the application secret. Each is a JSON key of the secret
    /// {slug}/{env}/server (the deployment id instead of the slug for a shared deployment) and is injected by ECS at task start, never as a plaintext environment variable.
    /// Keys left empty are ignored by the server (it treats an empty variable as unset). Public identifiers that the
    /// property defines (bundle id, Android package, store product id) are plain environment variables set from
    /// property.json instead; see <see cref="PropertyEnvironmentKeys"/>.
    /// </summary>
    public static class ServerSecretKeys
    {
        /// <summary>
        /// Key generated by Secrets Manager on creation (the break-glass admin token).
        /// </summary>
        public static readonly string GeneratedKey = "TK_ADMIN_TOKEN";

        /// <summary>
        /// Keys created empty, to be filled by an operator.
        /// </summary>
        public static readonly IReadOnlyList<string> ManualKeys = new List<string>
        {
            "TK_TOKEN_ENCRYPTION_KEY",
            "TK_STRIPE_SECRET_KEY",
            "TK_STRIPE_WEBHOOK_SECRET",
            "TK_STRIPE_PRICE_ID",
            "TK_APPSTORE_APP_APPLE_ID",
            "TK_APPSTORE_ISSUER_ID",
            "TK_APPSTORE_KEY_ID",
            "TK_APPSTORE_PRIVATE_KEY",
            "TK_GOOGLEPLAY_SERVICE_ACCOUNT_JSON",
            "TK_GOOGLEPLAY_PUBSUB_AUDIENCE",
            "TK_GOOGLEPLAY_PUBSUB_SERVICE_ACCOUNT",
            "TK_FACEBOOK_APP_ID",
            "TK_FACEBOOK_APP_SECRET",
            "TK_GOOGLE_WEB_CLIENT_ID",
            "TK_GOOGLE_IOS_CLIENT_ID",
            "TK_GOOGLE_ANDROID_CLIENT_ID",
            "TK_APPLE_SERVICES_ID",
            "TK_SMTP_USERNAME",
            "TK_SMTP_PASSWORD",
            "TK_BOOTSTRAP_ADMIN_EMAIL"
        };

        /// <summary>
        /// Environment variables set from the property's public identifiers (not secrets): TK_APPSTORE_BUNDLE_ID and
        /// TK_APPLE_BUNDLE_ID from mobile.bundleId, TK_GOOGLEPLAY_PACKAGE_NAME from mobile.androidPackage, and
        /// TK_APPSTORE_PRODUCT_ID and TK_GOOGLEPLAY_PRODUCT_ID from membership.storeProductId. Each is set only when
        /// the property defines the value.
        /// </summary>
        public static readonly IReadOnlyList<string> PropertyEnvironmentKeys = new List<string>
        {
            "TK_APPSTORE_BUNDLE_ID",
            "TK_APPLE_BUNDLE_ID",
            "TK_GOOGLEPLAY_PACKAGE_NAME",
            "TK_APPSTORE_PRODUCT_ID",
            "TK_GOOGLEPLAY_PRODUCT_ID"
        };

        /// <summary>
        /// Key of the platform secret {deployment}/{env}/platform (shared topology only), created empty: the initial
        /// password of the bootstrap platform administrator (setting platform.bootstrapAdminPassword). Supplied only
        /// from Secrets Manager; left empty, the server logs a one-time invitation token instead.
        /// </summary>
        public static readonly string PlatformBootstrapAdminPassword = "TK_PLATFORM_BOOTSTRAP_ADMIN_PASSWORD";

        /// <summary>
        /// Every key of the application secret.
        /// </summary>
        public static IReadOnlyList<string> AllKeys
        {
            get
            {
                List<string> keys = new List<string> { GeneratedKey };
                keys.AddRange(ManualKeys);
                return keys;
            }
        }
    }
}
