        #endregion

        #region Internal-Methods

        /// <summary>
        /// Request an export as the member, run the worker, and download the file.
        /// </summary>
        internal static async Task<JsonElement> ExportAsync(HttpFixture f, TestMember member, CancellationToken ct)
        {
            string exportId = Api.Str(await Api.ExpectAsync(f, HttpMethod.Post, "/api/v1/me/export", member.AccessToken, null, HttpStatusCode.Accepted, ct).ConfigureAwait(false), "exportId");
            await RunWorkerAsync(f, ct).ConfigureAwait(false);
            return await DownloadAsync(f, member, exportId, ct).ConfigureAwait(false);
        }

        #endregion

        #region Private-Methods

        private static async Task<int> RunWorkerAsync(HttpFixture f, CancellationToken ct)
        {
            AccountExportWorker worker = new AccountExportWorker(f.Services.AccountExports, f.Services.Logger);
            await using (worker.ConfigureAwait(false))
            {
                return await worker.RunOnceAsync(ct).ConfigureAwait(false);
            }
        }

        private static async Task<bool> StoredAsync(HttpFixture f, string exportId, CancellationToken ct)
        {
            return await f.Services.Integrations.ObjectStore.HeadAsync(AccountExportService.StorageLocation, f.Services.AccountExports.StorageKey(exportId), ct).ConfigureAwait(false) != null;
        }

        private static async Task<JsonElement> DownloadAsync(HttpFixture f, TestMember member, string exportId, CancellationToken ct)
        {
            JsonElement status = await Api.ExpectAsync(f, HttpMethod.Get, "/api/v1/me/export/" + exportId, member.AccessToken, null, HttpStatusCode.OK, ct).ConfigureAwait(false);
            Check.Equal("Ready", Api.Str(status, "status"), "Export ready");
            return await Api.ExpectAsync(f, HttpMethod.Get, Api.Str(status, "downloadUrl"), null, null, HttpStatusCode.OK, ct).ConfigureAwait(false);
        }

        private static TestCaseDescriptor Case(string caseId, string name, Func<HttpFixture, CancellationToken, Task> body)
        {
            return SuiteCases.Http(Id, caseId, name, body);
        }

        #endregion
    }
