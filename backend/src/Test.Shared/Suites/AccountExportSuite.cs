                    JsonElement metadata = file.GetProperty("metadata")[0];
                    Check.Equal("User", Api.Str(metadata, "targetType"), "Metadata target type");
                    Check.Equal(member.Id, Api.Str(metadata, "targetId"), "Metadata target");
