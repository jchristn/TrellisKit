                    JsonElement file = download.Body;
                    Check.Equal(exportId, Api.Str(file, "exportId"), "Export id in file");
                    foreach (string section in _Sections) Check.True(file.TryGetProperty(section, out JsonElement _), "Section " + section);
                    Check.Equal(member.Email, Api.Str(file.GetProperty("profile"), "email"), "Profile email");
