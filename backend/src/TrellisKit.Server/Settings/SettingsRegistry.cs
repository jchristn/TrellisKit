        private static string Optional(string value)
        {
            return value == null ? String.Empty : value.Trim();
        }

        private static string RequireKey(string value)
        {
            string trimmed = (value ?? String.Empty).Trim();
            try
            {
                if (Convert.FromBase64String(trimmed).Length == 32) return trimmed;
            }
            catch (FormatException)
            {
                // Reported below.
            }
            throw new ArgumentException("Must be a base64-encoded 32-byte key.");
        }

        private static string OptionalUrl(string value)
        {
            string trimmed = (value ?? String.Empty).Trim().TrimEnd('/');
            if (trimmed.Length == 0) return String.Empty;
            if (!Uri.TryCreate(trimmed, UriKind.Absolute, out Uri? uri) || (uri.Scheme != Uri.UriSchemeHttp && uri.Scheme != Uri.UriSchemeHttps))
                throw new ArgumentException("Must be an absolute http or https URL.");
            return trimmed;
        }

        private static string OptionalHttpsUrl(string value)
        {
            string trimmed = (value ?? String.Empty).Trim().TrimEnd('/');
            if (trimmed.Length == 0) return String.Empty;
            if (!Uri.TryCreate(trimmed, UriKind.Absolute, out Uri? uri) || uri.Scheme != Uri.UriSchemeHttps)
                throw new ArgumentException("Must be empty or an absolute https URL.");
            return trimmed;
        }

        private static string RequireHourMinute(string value)
        {
            string trimmed = (value ?? String.Empty).Trim();
            if (!System.Text.RegularExpressions.Regex.IsMatch(trimmed, "^([01][0-9]|2[0-3]):[0-5][0-9]$"))
                throw new ArgumentException("Must be a 24-hour time, HH:mm.");
            return trimmed;
        }

        private static long RequireLong(string value)
        {
            string trimmed = String.IsNullOrWhiteSpace(value) ? "0" : value.Trim();
            if (!Int64.TryParse(trimmed, System.Globalization.NumberStyles.None, System.Globalization.CultureInfo.InvariantCulture, out long number))
                throw new ArgumentException("Must be a whole number.");
            return number;
        }

        private static string RequireText(string value)
        {
            if (String.IsNullOrWhiteSpace(value)) throw new ArgumentException("A value is required.");
            return value.Trim();
        }

