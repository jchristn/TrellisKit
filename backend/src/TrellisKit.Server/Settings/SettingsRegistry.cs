        public static readonly IReadOnlyList<SettingFieldDefinition> All = Build().Concat(AiSettingFields.Build()).Concat(UsageSettingFields.Build()).Concat(JobSettingFields.Build()).Concat(ContentReviewSettingFields.Build()).Concat(LibrarySettingFields.Build()).Concat(EventsSettingFields.Build()).Concat(DirectorySettingFields.Build()).Concat(Phase5SettingFields.Build()).Concat(AdminSummarySettingFields.Build()).Concat(SavesSettingFields.Build()).ToList();

        #endregion

        #region Public-Methods

        /// <summary>
        /// Find a definition by key (case-insensitive).
        /// </summary>
        /// <param name="key">Key.</param>
        /// <returns>Definition, or null.</returns>
        public static SettingFieldDefinition? Find(string key)
        {
            if (String.IsNullOrWhiteSpace(key)) return null;
            return All.FirstOrDefault(d => String.Equals(d.Key, key, StringComparison.OrdinalIgnoreCase));
        }

